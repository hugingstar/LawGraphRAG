_GROUP_PATTERNS = [(code, re.compile(pattern)) for code, pattern in _GROUP_RULES]


def group_of(law_name: str | None) -> str:
    """법령명으로 분야 묶음 코드를 정한다. 판단 못 하면 'etc'."""
    if not law_name:
        return "etc"
    for code, pattern in _GROUP_PATTERNS:
        if pattern.search(law_name):
            return code
    return "etc"


def heat_color(ratio: float | None) -> str:
    """0..1 을 인용도 램프의 한 칸으로 옮긴다. 값이 없으면 중립색."""
    if ratio is None:
        return NEUTRAL
    index = int(max(0.0, min(1.0, ratio)) * (len(HEAT_RAMP) - 1))
    return HEAT_RAMP[index]


